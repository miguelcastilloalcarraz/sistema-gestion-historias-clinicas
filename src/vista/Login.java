    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());

        //validación de campos vacíos
        if (usuario.isEmpty() || contrasena.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese usuario y contraseña.", "Campos incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        //validación de usuario y contraseña
        modelo.Usuario u;
        try {
            u = modelo.Datos.autenticar(usuario, contrasena);
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de conexión", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (u == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Usuario o contraseña incorrectos.", "Acceso denegado",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        PrincipalFrame principal = new PrincipalFrame();
        principal.mostrarBienvenida(usuario);
        principal.setVisible(true);
        dispose();
    }//GEN-LAST:event_btnIngresarActionPerformed

