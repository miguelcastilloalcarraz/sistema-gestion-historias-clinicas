    //método para restaurar los botones
    private void restaurarBotones() {
        btnInicio.setBackground(COLOR_NORMAL);
        btnPacientes.setBackground(COLOR_NORMAL);
        btnConsultas.setBackground(COLOR_NORMAL);
        btnReferencias.setBackground(COLOR_NORMAL);
        btnReportes.setBackground(COLOR_NORMAL);
        btnCerrarSesion.setBackground(COLOR_NORMAL);

        btnInicio.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_inicio.jpg")));
        btnPacientes.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_pacientes.jpg")));
        btnConsultas.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_consultas.jpg")));
        btnReferencias.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_referencias.jpg")));
        btnReportes.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_reportes.jpg")));
        btnCerrarSesion.setIcon(new ImageIcon(getClass().getResource("/imagenes/logo_cerrarSesion.jpg")));
    }

    //método para seleccionar un botón
    private void seleccionarBoton(JButton boton, String rutaIconoSeleccionado) {
        restaurarBotones();
        boton.setBackground(COLOR_SELECCIONADO);
        boton.setIcon(new ImageIcon(getClass().getResource(rutaIconoSeleccionado)));
    }

