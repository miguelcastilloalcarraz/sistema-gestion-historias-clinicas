    //método para generar el reporte según la opción elegida
    private void generarReporte() {
        try {
            int dni = Integer.parseInt(txtBuscarDNI.getText().trim());
            Paciente p = Datos.buscarPaciente(dni);
            if (p == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró un paciente con DNI " + dni + ".",
                        "No encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            StringBuilder sb = new StringBuilder();
            switch (cboOpcionReporte.getSelectedIndex()) {
                case 0 -> //Paciente ingresado
                    sb.append(p.toString());
                case 1 -> { //Referencia hospitalaria
                    var refs = Datos.referenciasDe(dni);
                    if (refs.isEmpty()) {
                        sb.append("El paciente no tiene referencias hospitalarias registradas.");
                    } else {
                        for (ReferenciaHospitalaria r : refs) {
                            sb.append(r.toString()).append("\n");
                        }
                    }
                }
                case 2 -> { //Consulta médica
                    var cons = Datos.consultasDe(dni);
                    if (cons.isEmpty()) {
                        sb.append("El paciente no tiene consultas médicas registradas.");
                    } else {
                        for (ConsultaMedica c : cons) {
                            sb.append(c.toString()).append("\n");
                        }
                    }
                }
                default -> { //Historial clínico completo (clase de solo reporte)
                    HistorialClinico historial = new HistorialClinico(p,
                            Datos.consultasDe(dni), Datos.referenciasDe(dni));
                    sb.append(historial.generarReporte());
                }
            }
            txtAreaReporte.setText(sb.toString());
            txtAreaReporte.setCaretPosition(0);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un DNI válido para generar el reporte.", "Dato inválido",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }

