    //método para buscar al paciente y cargar su última consulta
    private void buscarPaciente() {
        try {
            int dni = Integer.parseInt(txtBuscarDNI.getText().trim());
            Paciente p = Datos.buscarPaciente(dni);
            if (p == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró un paciente con DNI " + dni + ".",
                        "No encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            txtDNI.setText(String.valueOf(p.getDni()));
            txtNombres.setText(p.getNombres());
            txtApellidos.setText(p.getApellidos());
            ArrayList<ConsultaMedica> consultas = Datos.consultasDe(dni);
            if (!consultas.isEmpty()) {
                ConsultaMedica ultima = consultas.get(consultas.size() - 1);
                txtAreaDiagnostico.setText(ultima.getDiagnostico());
                txtAreaTratamiento.setText(ultima.getTratamiento());
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un DNI válido para buscar.", "Dato inválido",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }

    //método para registrar la referencia hospitalaria
    private void guardarReferencia() {
        try {
            int dni = Integer.parseInt(txtDNI.getText().trim());
            Paciente paciente = Datos.buscarPaciente(dni);
            if (paciente == null) {
                JOptionPane.showMessageDialog(this,
                        "Primero busque un paciente registrado por su DNI.",
                        "Paciente no encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            String diagnostico = txtAreaDiagnostico.getText().trim();
            if (diagnostico.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "El diagnóstico es obligatorio para generar la referencia.",
                        "Campos incompletos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            //si no se ingresa código lo genera la base de datos
            String codTexto = txtCodReferencia.getText().trim();
            int codigo = codTexto.isEmpty() ? 0 : Integer.parseInt(codTexto);
            LocalDate fecha = LocalDate.parse(txtFechaCons.getText().trim(), FORMATO_FECHA);
            Medico medico = Datos.buscarMedico(Integer.parseInt(cboColMedico.getSelectedItem().toString()));
            String observaciones = "Diagnóstico: " + diagnostico
                    + "\nTratamiento: " + txtAreaTratamiento.getText().trim();

            ReferenciaHospitalaria referencia = new ReferenciaHospitalaria(codigo,
                    cboHospitalRef.getSelectedItem().toString(), medico, paciente,
                    fecha, observaciones, "Pendiente");
            int codGenerado = Datos.registrarReferencia(referencia);
            JOptionPane.showMessageDialog(this,
                    "Referencia registrada correctamente (código " + codGenerado + ", estado Pendiente).");
            limpiarFormulario();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Revise el DNI y el código de referencia: deben ser numéricos.",
                    "Datos inválidos", JOptionPane.ERROR_MESSAGE);
        } catch (java.time.format.DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese la fecha en formato dd/mm/aaaa.", "Fecha inválida",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de base de datos", JOptionPane.ERROR_MESSAGE);
        }
    }

    //método para eliminar una referencia por su código
    private void eliminarReferencia() {
        try {
            int codigo = Integer.parseInt(txtCodReferencia.getText().trim());
            if (Datos.buscarReferencia(codigo) == null) {
                JOptionPane.showMessageDialog(this,
                        "No existe una referencia con el código " + codigo + ".",
                        "No encontrada", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int opcion = JOptionPane.showConfirmDialog(this,
                    "¿Seguro de eliminar la referencia " + codigo + "?",
                    "Confirmación", JOptionPane.YES_NO_OPTION);
            if (opcion == JOptionPane.YES_OPTION) {
                Datos.eliminarReferencia(codigo);
                JOptionPane.showMessageDialog(this, "Referencia eliminada.");
                limpiarFormulario();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el código de la referencia a eliminar.", "Dato inválido",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de base de datos", JOptionPane.ERROR_MESSAGE);
        }
    }
