    //método para buscar al paciente por DNI
    private void buscarPaciente() {
        try {
            int dni = Integer.parseInt(txtBuscarDNI.getText().trim());
            Paciente p = Datos.buscarPaciente(dni);
            if (p == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró un paciente con DNI " + dni + ". Regístrelo primero en Pacientes.",
                        "No encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            txtDNI.setText(String.valueOf(p.getDni()));
            txtNombres.setText(p.getNombres());
            txtApellidos.setText(p.getApellidos());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un DNI válido para buscar.", "Dato inválido",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }

    //método para registrar la consulta médica
    private void guardarConsulta() {
        try {
            int dni = Integer.parseInt(txtDNI.getText().trim());
            Paciente paciente = Datos.buscarPaciente(dni);
            if (paciente == null) {
                JOptionPane.showMessageDialog(this,
                        "Primero busque un paciente registrado por su DNI.",
                        "Paciente no encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            String motivo = txtAreaMotivoC.getText().trim();
            String diagnostico = txtAreaDiagnostico.getText().trim();
            if (motivo.isEmpty() || diagnostico.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "El motivo de consulta y el diagnóstico son obligatorios.",
                        "Campos incompletos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            LocalDate fecha = LocalDate.parse(txtFechaCons.getText().trim(), FORMATO_FECHA);
            LocalTime hora = ((Date) spHora.getValue()).toInstant()
                    .atZone(ZoneId.systemDefault()).toLocalTime().withSecond(0).withNano(0);
            Medico medico = Datos.buscarMedico(Integer.parseInt(cboColMedico.getSelectedItem().toString()));
            String especialidad = cboGenero.getSelectedItem().toString();

            ConsultaMedica consulta = new ConsultaMedica(0, motivo,
                    especialidad, diagnostico, txtAreaTratamiento.getText().trim(),
                    fecha, hora, paciente, medico);
            int id = Datos.registrarConsulta(consulta);
            JOptionPane.showMessageDialog(this,
                    "Consulta registrada correctamente (ID " + id + ").");
            limpiarFormulario();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Busque primero al paciente por su DNI.", "Datos inválidos",
                    JOptionPane.ERROR_MESSAGE);
        } catch (java.time.format.DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese la fecha de consulta en formato dd/mm/aaaa.", "Fecha inválida",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de base de datos", JOptionPane.ERROR_MESSAGE);
        }
    }


