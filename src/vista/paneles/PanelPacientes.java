    //método para leer y validar los datos del formulario
    private Paciente leerFormulario() throws Exception {
        int dni = Integer.parseInt(txtDNI.getText().trim());
        String nombres = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        if (nombres.isEmpty() || apellidos.isEmpty()) {
            throw new Exception("Nombres y apellidos son obligatorios.");
        }
        LocalDate fechaNac = LocalDate.parse(txtFechaNac.getText().trim(), FORMATO_FECHA);
        if (fechaNac.isAfter(LocalDate.now())) {
            throw new Exception("La fecha de nacimiento no puede ser futura.");
        }
        String direccion = txtDireccion.getText().trim();
        char genero = cboGenero.getSelectedItem().toString().charAt(0);
        int telefono = Integer.parseInt(txtTelefono.getText().trim());
        String grupoSanguineo = cboGrupoSa.getSelectedItem().toString();
        String tipoSeguro = cboTipoSeguro.getSelectedItem().toString();
        double peso = Double.parseDouble(txtPeso.getText().trim());
        double talla = Double.parseDouble(txtTalla.getText().trim());
        if (peso <= 0 || talla <= 0) {
            throw new Exception("Peso y talla deben ser valores positivos.");
        }
        return new Paciente(dni, nombres, apellidos, fechaNac, direccion,
                genero, telefono, grupoSanguineo, tipoSeguro, peso, talla);
    }

    private void guardarPaciente() {
        try {
            Paciente nuevo = leerFormulario();
            if (Datos.buscarPaciente(nuevo.getDni()) != null) {
                JOptionPane.showMessageDialog(this,
                        "Ya existe un paciente con ese DNI. Use el botón Editar.",
                        "DNI duplicado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            Datos.registrarPaciente(nuevo);
            JOptionPane.showMessageDialog(this, "Paciente registrado correctamente.");
            limpiarFormulario();
        } catch (Exception ex) {
            mostrarErrorFormulario(ex);
        }
    }

    private void editarPaciente() {
        try {
            Paciente editado = leerFormulario();
            Paciente existente = Datos.buscarPaciente(editado.getDni());
            if (existente == null) {
                JOptionPane.showMessageDialog(this,
                        "No existe un paciente con ese DNI.", "No encontrado",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            Datos.actualizarPaciente(editado);
            JOptionPane.showMessageDialog(this, "Paciente actualizado correctamente.");
            limpiarFormulario();
        } catch (Exception ex) {
            mostrarErrorFormulario(ex);
        }
    }

    private void eliminarPaciente() {
        try {
            int dni = Integer.parseInt(txtDNI.getText().trim());
            Paciente p = Datos.buscarPaciente(dni);
            if (p == null) {
                JOptionPane.showMessageDialog(this,
                        "No existe un paciente con ese DNI.", "No encontrado",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            //no se puede eliminar un paciente con consultas registradas
            if (!Datos.consultasDe(dni).isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "No se puede eliminar: el paciente tiene consultas registradas.",
                        "Operación no permitida", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int opcion = JOptionPane.showConfirmDialog(this,
                    "¿Seguro de eliminar al paciente " + p.getNombres() + " " + p.getApellidos() + "?",
                    "Confirmación", JOptionPane.YES_NO_OPTION);
            if (opcion == JOptionPane.YES_OPTION) {
                Datos.eliminarPaciente(dni);
                JOptionPane.showMessageDialog(this, "Paciente eliminado.");
                limpiarFormulario();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el DNI del paciente a eliminar en el formulario.",
                    "Dato inválido", JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Operación no permitida", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void buscarPaciente() {
        try {
            int dni = Integer.parseInt(txtBuscarDNI.getText().trim());
            Paciente p = Datos.buscarPaciente(dni);
            if (p == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró un paciente con DNI " + dni + ".",
                        "No encontrado", JOptionPane.WARNING_MESSAGE);
                return;
            }
            //método para cargar los datos del paciente en el formulario
            txtDNI.setText(String.valueOf(p.getDni()));
            txtNombres.setText(p.getNombres());
            txtApellidos.setText(p.getApellidos());
            txtFechaNac.setText(p.getFacheNac().format(FORMATO_FECHA));
            txtDireccion.setText(p.getDireccion());
            cboGenero.setSelectedItem(String.valueOf(p.getGenero()));
            txtTelefono.setText(String.valueOf(p.getTelefono()));
            cboGrupoSa.setSelectedItem(p.getGrupoSanguineo());
            cboTipoSeguro.setSelectedItem(p.getTipoSeguro());
            txtPeso.setText(String.valueOf(p.getPeso()));
            txtTalla.setText(String.valueOf(p.getTalla()));
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un DNI válido para buscar.", "Dato inválido",
                    JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void mostrarErrorFormulario(Exception ex) {
        String mensaje = ex instanceof NumberFormatException || ex instanceof java.time.format.DateTimeParseException
                ? "Revise los datos: DNI y teléfono deben ser numéricos, la fecha en formato dd/mm/aaaa, y peso/talla decimales."
                : ex.getMessage();
        JOptionPane.showMessageDialog(this, mensaje, "Datos inválidos", JOptionPane.ERROR_MESSAGE);
    }

    //método para limpiar la información ingresada en el formulario
    private void limpiarFormulario() {
        txtDNI.setText("");
        txtNombres.setText("");
        txtApellidos.setText("");
        txtFechaNac.setText("");
        txtDireccion.setText("");
        cboGenero.setSelectedIndex(0);
        txtTelefono.setText("");
        cboGrupoSa.setSelectedIndex(0);
        cboTipoSeguro.setSelectedIndex(0);
        txtPeso.setText("");
        txtTalla.setText("");
    }

